namespace MirIgrushek.Models
{
    /// <summary>
    /// Роли пользователей системы. Определяют доступный функционал.
    /// </summary>
    public enum UserRole
    {
        Guest,    // Гость: просмотр товаров без фильтрации, сортировки, поиска
        Client,   // Авторизированный клиент: просмотр товаров
        Manager,  // Менеджер: просмотр товаров (фильтр/сортировка/поиск) и заказов
        Admin     // Администратор: полный доступ к товарам и заказам
    }
}
